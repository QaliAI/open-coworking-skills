#!/usr/bin/env python3
"""Generate operator-facing docs from catalog/playbooks.yaml and catalog/skills.yaml.

Writes:
  docs/CHOOSE_A_PLAYBOOK.md
  docs/operators/SKILL_DIRECTORY.md

Usage:
  python scripts/generate_operator_docs.py
  python scripts/generate_operator_docs.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent


def _playbook_page(data: dict) -> str:
    lines = [
        "# Choose a playbook",
        "",
        "Start from the question you already have. You do not need the skill's file name.",
        "Each playbook is a sequence of existing skills. The procedures ship inside",
        "`coworking-operator-playbooks` so an installed copy still contains them.",
        "",
        "Paste this to an assistant that has the skills installed:",
        "",
        "> I operate a coworking space. Use my installed OpenCoworking Skills. Ask what",
        "> systems I use and what problem I am trying to solve. Tell me the minimum exports",
        "> you need. Do not request unnecessary member PII. Explain any metric before using it.",
        "",
        "A new-location or presale playbook is not shipped. Those skills are still planned.",
        "",
        "| Question | Playbook | Skills, in order |",
        "|---|---|---|",
    ]
    for item in data.get("playbooks") or []:
        skills = " → ".join(f"`{name}`" for name in item.get("skills") or [])
        link = Path("..") / item["reference"]
        lines.append(
            f"| {item['question']} | [{item['id']}]({link.as_posix()}) | {skills} |")
    lines += [
        "",
        "Exports, if you have them, can also go through the deterministic CLI.",
        "From a checkout: `opencoworking demo` runs the synthetic health check.",
        "Your own folder: `opencoworking health-check --input <folder> --output <folder> "
        "--client \"Name\"`.",
        "",
        "Generated from `catalog/playbooks.yaml`. Do not edit this file by hand.",
        "",
    ]
    return "\n".join(lines)


def _directory(catalog: dict) -> str:
    lines = [
        "# Operator skill directory",
        "",
        "Generated from `catalog/skills.yaml`. Maturity, risk, and the problem statement",
        "come from that file. Prompts and formulas live in each skill.",
        "",
        "| Skill | Maturity | Risk | Modes | Who it is for | Problem | Needs | Returns |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for entry in catalog.get("skills") or []:
        if entry.get("status") == "planned":
            continue
        modes = "+".join(entry.get("modes") or [])
        lines.append(
            f"| `{entry['name']}` | {entry.get('status')} | {str(entry.get('risk', '')).upper()} "
            f"| {modes} | {entry.get('primary_user', '')} | {entry.get('problem', '')} "
            f"| {entry.get('inputs', '')} | {entry.get('outputs', '')} |")
    lines += [
        "",
        "## Planned, not installable yet",
        "",
    ]
    for entry in catalog.get("skills") or []:
        if entry.get("status") != "planned":
            continue
        lines.append(f"- `{entry['name']}` — {entry.get('problem', '')}")
    lines += [
        "",
        "Modes are manual, export, or both. No shipped skill requires a live login.",
        "Risk R0 is read-only analysis. Risk R1 drafts something a human sends or decides.",
        "",
        "Generated file. Do not edit by hand.",
        "",
    ]
    return "\n".join(lines)


def render() -> dict[str, str]:
    playbooks = yaml.safe_load((REPO / "catalog" / "playbooks.yaml").read_text(encoding="utf-8"))
    catalog = yaml.safe_load((REPO / "catalog" / "skills.yaml").read_text(encoding="utf-8"))
    problems = []
    for item in playbooks.get("playbooks") or []:
        path = REPO / item["reference"]
        if not path.is_file():
            problems.append(f"missing playbook reference {item['reference']}")
        for name in item.get("skills") or []:
            if not (REPO / ".agents" / "skills" / name).is_dir():
                problems.append(f"playbook {item['id']} names missing skill {name}")
    if problems:
        raise SystemExit("\n".join(problems))
    return {
        "docs/CHOOSE_A_PLAYBOOK.md": _playbook_page(playbooks),
        "docs/operators/SKILL_DIRECTORY.md": _directory(catalog),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    pages = render()
    drifted = []
    for rel, text in pages.items():
        path = REPO / rel
        if args.check:
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != text:
                drifted.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if drifted:
        print("out of date: " + ", ".join(drifted), file=sys.stderr)
        return 1
    if args.check:
        print("operator docs match the catalog")
    return 0


if __name__ == "__main__":
    sys.exit(main())
